FOOT = re.compile(r'^\s*[〔﹝]')
PAGE = re.compile(r'^\s*\d+\s*语文|^第.单元')
def clean_body(fname, cut_at):
    p = os.path.join(BASE, fname + '.txt')
    lines = open(p, encoding='utf-8').read().split('\n')
    out = []
    skipped_foot = False
    for ln in lines:
        s = ln.strip()
        if not s:
            continue
        if '选自' in s and s.startswith(('选','自')) and not s.startswith(('自','《')):
            continue
        # page markers
        if re.match(r'^\s*\d+\s*语文', ln) or re.match(r'^第?[一二三四五六]?\s*单元\s*\d+\s*$', ln) or s == '版' or s == '编' or s == '统':
            continue
        # footnotes start
        if FOOT.match(ln) or s.startswith('①') or (s.startswith('〔') is False and False):
            continue
        # footnote-start letters like "a 选自" or "a 〔"
        if re.match(r'^[a-z]\s[（(＇]', s) or re.match(r'^[a-z]\s*[〔]', s):
            continue
        # image captions
        if (re.search(r'【(局部)?】', s) and ' 作' in s) or (('作' == s[-1:]) and ('图' in s or '像' in s)):
            if '〔' not in s:
                continue
        # isolated footnote letters marking lines (single latin trigraph)
        # project footnote numbering like "②" removed
        out.append(ln)
    # remove inline latin letters and @#digits
    txt = '\n'.join(out)
    txt = re.sub(r'(?<![a-zA-Z])[a-zA-Z](?![a-zA-Z])', '', txt)
    txt = re.sub(r'[@#]\d+', '', txt)
    return txt